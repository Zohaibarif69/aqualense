// Generates supabase/seed.sql from src/mocks/data.ts so the database starts with the same data as the offline app:
//   real:  monitoring sites, environmental indicators, discharge series (AquaConnect snapshot, src/data/aquaconnect.json)
//   demo:  citizen reports, photos, AI findings, reviews, notifications
// Usage: npm run data:import (only to refresh the snapshot), then npm run db:seed:generate
import { writeFileSync } from "node:fs";
import * as d from "../src/mocks/data.ts";

const base = Date.parse(d.ago(0));
const str = (v) => (v == null || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v == null ? "NULL" : String(v));
const bool = (v) => (v ? "true" : "false");
const arr = (v) => (v == null ? "NULL" : `array[${v.map(str).join(",")}]::text[]`);
const arrOrEmpty = (v) => (v?.length ? arr(v) : "'{}'::text[]");
const json = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
// Absolute timestamps for the real snapshot (they must not drift with the moment the seed is run).
const abs = (iso) => (iso ? `'${iso}'::timestamptz` : "NULL");
const ts = (iso) => {
  if (!iso) return "NULL";
  const s = Math.round((Date.parse(iso) - base) / 1000);
  return `now() ${s < 0 ? "-" : "+"} interval '${Math.abs(s)} seconds'`;
};

const out = [];
const insert = (table, cols, rows, conflict = "on conflict do nothing") => {
  if (!rows.length) return;
  out.push(`insert into public.${table} (${cols.join(", ")}) values\n  ${rows.map((r) => `(${r.join(", ")})`).join(",\n  ")}\n${conflict};\n`);
};

out.push("-- AquaLens seed data. Generated by scripts/generate-seed.mjs.");
out.push(`-- REAL: ${d.sites.length} monitoring sites, environmental indicators and discharge series from the AquaConnect snapshot`);
out.push(`--       (forecast ${d.dataset.forecastStart} to ${d.dataset.forecastEnd}). Screening outputs, not probabilities of ecological damage.`);
out.push("-- DEMO: citizen reports, photos, AI findings, expert reviews and notifications (illustrative only).");
out.push("-- Safe to re-run: the AquaConnect rows and the demo reports are replaced; anything else is kept.\n");

out.push("-- Remove the old Portland demo sites (indicators and discharge go with them) and refresh the demo reports.");
out.push("delete from public.sites where id in ('S-101','S-102','S-103','S-104','S-105','S-106');");
out.push(`delete from public.observations where id in (${d.observations.map((o) => str(o.id)).join(", ")});`);
out.push(`delete from public.notifications where id in (${d.notifications.map((n) => str(n.id)).join(", ")});`);
out.push("delete from public.environmental_indicators;");
out.push("delete from public.discharge_series;\n");

insert("sites", ["id","name","city","latitude","longitude","waterbody_name","site_type","upstream_site_ids","downstream_site_ids","last_updated_at","data_availability","monitoring_priority","priority_class","priority_score","has_sensor"],
  d.sites.map((s) => [str(s.id), str(s.name), str(s.city), num(s.latitude), num(s.longitude), str(s.waterbodyName), str(s.siteType), arrOrEmpty(s.upstreamSiteIds), arrOrEmpty(s.downstreamSiteIds), abs(d.dataset.issuedAt), str(s.dataAvailability), str(s.monitoringPriority), str(s.priorityClass), num(s.priorityScore), bool(s.hasSensor)]), "on conflict (id) do update set name = excluded.name, city = excluded.city, latitude = excluded.latitude, longitude = excluded.longitude, site_type = excluded.site_type, upstream_site_ids = excluded.upstream_site_ids, downstream_site_ids = excluded.downstream_site_ids, last_updated_at = excluded.last_updated_at, data_availability = excluded.data_availability, monitoring_priority = excluded.monitoring_priority, priority_class = excluded.priority_class, priority_score = excluded.priority_score");

insert("observations", ["id","created_at","updated_at","observed_at","latitude","longitude","site_id","place_name","location_precision","categories","description","status","submitted_by","seen_before"],
  d.observations.map((o) => [str(o.id), ts(o.createdAt), ts(o.updatedAt), ts(o.observedAt), num(o.location.latitude), num(o.location.longitude), str(o.location.siteId), str(o.location.placeName), str(o.location.precision), arrOrEmpty(o.categories), str(o.description), str(o.status), str(o.submittedBy), str(o.seenBefore)]));

insert("photos", ["id","observation_id","filename","mime_type","size_bytes","url","uploaded_at","quality_status"],
  d.photos.map((p) => {
    const o = d.observations.find((x) => x.photoIds.includes(p.id));
    return [str(p.id), str(o?.id), str(p.filename), str(p.mimeType), num(p.sizeBytes), str(p.uploadedUrl ?? p.previewUrl), o ? ts(o.createdAt) : "now()", str(p.qualityStatus)];
  }));

insert("ai_analyses", ["id","observation_id","status","model_name","model_version","analyzed_at","findings","message"],
  d.analyses.map((a) => [str(a.id), str(a.observationId), str(a.status), str(a.modelName), str(a.modelVersion), ts(a.analyzedAt), json(a.findings), str(a.message)]));

insert("expert_reviews", ["id","observation_id","reviewer_id","status","decision","corrected_categories","public_note","internal_note","reason_code","reviewed_at"],
  d.reviews.map((r) => [str(r.id), str(r.observationId), str(r.reviewerId), str(r.status), str(r.decision), arr(r.correctedCategories), str(r.publicNote), str(r.internalNote), str(r.reasonCode), ts(r.reviewedAt)]));

insert("timeline_events", ["id","observation_id","at","type","label","detail"],
  d.timeline.map((t) => [str(t.id), str(t.observationId), ts(t.at), str(t.type), str(t.label), str(t.detail)]));

insert("notifications", ["id","user_id","type","title","body","created_at","read","observation_id"],
  d.notifications.map((n) => [str(n.id), "NULL", str(n.type), str(n.title), str(n.body), ts(n.createdAt), bool(n.read), str(n.observationId)]));

insert("environmental_indicators", ["id","site_id","name","value","unit","level","description","source","observed_at","issued_at","valid_from","valid_to","data_status","limitations","kind"],
  d.indicators.map((i) => [str(i.id), str(i.siteId), str(i.name), num(i.value), str(i.unit), str(i.level), str(i.description), str(i.source), abs(i.observedAt), abs(i.issuedAt), abs(i.validFrom), abs(i.validTo), str(i.dataStatus), arrOrEmpty(i.limitations), str(i.kind)]));

insert("discharge_series", ["site_id","date","observed","forecast"],
  d.sites.flatMap((s) => d.outlook(s.id).map((p) => [str(s.id), abs(p.date), num(p.observed), num(p.forecast)])));

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log("Wrote supabase/seed.sql");
